def migrate_default_text(raw):
    """Return an English upgrade plan in memory; never write before snapshot."""
    from importlib.resources import files
    defaults = tomllib.loads(files("tvlk_ai_router").joinpath("data/router.example.toml").read_text())
    doc = tomlkit.parse(raw.decode())
    changed = False
    for name, old_hash in LEGACY_DEFAULT_TEXT.items():
        keys = name.split(".")
        target, replacement = doc, defaults
        for key in keys[:-1]:
            target, replacement = target[key], replacement[key]
        current = target[keys[-1]]
        if digest(str(current).encode()) == old_hash:
            target[keys[-1]] = replacement[keys[-1]]
            changed = True
    return tomlkit.dumps(doc).encode() if changed else raw


def routing_block(d):
    lines = [BEGIN, "## TVLK-OpenAI-Router automatic routing", "Delegate substantive work to these custom agents, within current permissions and higher-priority instructions."]
    lines.append("Use the tvlk-ai-router management Skill for router help, configuration, usage review, disable, enable, backup and restore requests; do not delegate those requests to executors.")
    for role, a in d["agents"].items():
        lines.append(f"- {role}: {a['name']} — {a['model']} / {a['reasoning_effort']} — {a['description']}")
    r = d["routing"]
    lines += [f"Keep at most one active executor and at most {r['max_escalations_per_request']} escalation per original request.",
              "Reuse the specialist for follow-ups on the same task when possible." if r["reuse_executor_for_followups"] else "Pass necessary context for follow-ups; reusing the specialist is optional.",
              "Select the native custom role by name; a generic subagent task_name does not load a role.",
              "If the requested role is unavailable, stop and report; do not silently switch models. The coordinator reviews artifacts, evidence and unresolved issues.",
              r["rules"].strip(), END]
    return "\n".join(lines) + "\n"


def strip_block(text):
    if text.count(BEGIN) != text.count(END) or text.count(BEGIN) > 1:
        raise RouterError("Managed instruction markers are missing or duplicated", 4)
    if BEGIN not in text:
        return text, None
    start, finish = text.index(BEGIN), text.index(END) + len(END)
    if finish < start:
        raise RouterError("Managed instruction markers are out of order", 4)
    if text[finish:finish + 1] == "\n":
        finish += 1
    return text[:start] + text[finish:], text[start:finish]


def get_keys(doc):
    values = {}
    for key in KEYS:
        v = doc
        found = True
        for part in key.split("."):
            if not isinstance(v, dict) or part not in v:
                found = False
                break
            v = v[part]
        values[key] = {"present": found, "value": v if found else None}
    return values


def desired_keys(d):
    return {"model": {"present": True, "value": d["coordinator"]["model"]},
            "model_reasoning_effort": {"present": True, "value": d["coordinator"]["reasoning_effort"]},
            "agents.enabled": {"present": True, "value": True}}


def merge_keys(raw, values):
    try:
        doc = tomlkit.parse(raw.decode())
        for key, item in values.items():
            parts = key.split(".")
            target = doc
            for part in parts[:-1]:
                if part not in target:
                    if not item["present"]:
                        break
                    target[part] = tomlkit.table()
                target = target[part]
            else:
                if item["present"]:
                    target[parts[-1]] = item["value"]
                elif parts[-1] in target:
                    del target[parts[-1]]
        if "agents" in doc and not doc["agents"]:
            del doc["agents"]
        result = tomlkit.dumps(doc).encode()
        tomllib.loads(result.decode())
        return result
    except (ValueError, TypeError, AttributeError) as exc:
        raise RouterError("Cannot safely merge the existing Codex TOML: " + str(exc), 4) from exc


def model_check(home, d):
    cache = home / "models_cache.json"
    if not cache.is_file():
        return {"status": "unverified", "reason": "models_cache.json is missing; sign in to the target Codex and refresh its model list first"}
    try:
        payload = json.loads(cache.read_bytes())
        models = {m["slug"]: m for m in payload["models"]}
        for a in [d["coordinator"], *d["agents"].values()]:
            model = models.get(a["model"])
            if not model or model.get("visibility") in ("hide", "hidden"):
                raise RouterError("Model unavailable in the client cache: " + a["model"], 3)
            efforts = {e["effort"] if isinstance(e, dict) else e for e in model.get("supported_reasoning_levels", [])}
            if a["reasoning_effort"] not in efforts:
                raise RouterError("Reasoning effort unsupported by the client cache: " + a["model"] + " / " + a["reasoning_effort"], 3)
        return {"status": "cache_matched", "client_version": payload.get("client_version"),
                "fetched_at": payload.get("fetched_at"), "runtime": "unverified"}
    except (KeyError, ValueError, TypeError) as exc:
        raise RouterError("Unrecognized model cache format", 3) from exc


# Only explicitly recognized preference keys are merged; all other mixed state stays
# in the full snapshot. Full restore is a separate, explicitly selected operation.
UI_PREFS = {"electron-main-window-bounds", "electron-avatar-overlay-bounds",
            "electron-internal-update-cdn-enabled", "electron-initial-follow-up-queue-mode"}
ATOM_PREFS = {"desktop-link-default-destination", "flat-project-sidebar-preferences-v1",
              "composer-model-picker-selection-mode-v1", "composer-auto-context-enabled",
              "app-shell:right-panel-width:v3", "preferred-non-full-access-agent-mode-by-host-id"}


def merge_preferences(current, saved):
    now, old = json.loads(current or b"{}"), json.loads(saved or b"{}")
    result = copy.deepcopy(now)
    for key in UI_PREFS:
        result.pop(key, None)
        if key in old:
            result[key] = old[key]
    key = "electron-persisted-atom-state"
    if key in now or key in old:
        result.setdefault(key, {})
        for name in ATOM_PREFS:
            result[key].pop(name, None)
            if name in old.get(key, {}):
                result[key][name] = old[key][name]
    return json_bytes(result) if result != now else current
