ROLES = ("coding", "writing", "product", "analysis")
BEGIN = "<!-- BEGIN TVLK-OPENAI-ROUTER V1 -->"
END = "<!-- END TVLK-OPENAI-ROUTER V1 -->"
KEYS = ("model", "model_reasoning_effort", "agents.enabled")


class RouterError(Exception):
    def __init__(self, message, code=2):
        super().__init__(message)
        self.code = code


def digest(data):
    return hashlib.sha256(data).hexdigest()


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode()


def parse(raw):
    try:
        d = tomllib.loads(raw.decode("utf-8"))
    except (ValueError, UnicodeError) as exc:
        raise RouterError("Cannot parse TOML: " + str(exc)) from exc

    def shape(v, names, label):
        if not isinstance(v, dict) or set(v) != set(names):
            raise RouterError(f"{label} must contain exactly: {', '.join(names)}")

    def text(v, label):
        if not isinstance(v, str) or not v.strip() or "\x00" in v:
            raise RouterError(label + " must be a non-empty string")

    shape(d, ("schema_version", "coordinator", "routing", "execution", "agents", "backup"), "root configuration")
    if type(d["schema_version"]) is not int or d["schema_version"] != 1:
        raise RouterError("Unsupported schema_version")
    shape(d["coordinator"], ("model", "reasoning_effort"), "coordinator")
    shape(d["agents"], ROLES, "agents")
    names = []
    for role, a in [("coordinator", d["coordinator"]), *d["agents"].items()]:
        if role != "coordinator":
            shape(a, ("name", "model", "reasoning_effort", "description", "instructions"), role)
            if not isinstance(a["name"], str) or not re.fullmatch(r"tvlk_ai_route_[a-z][a-z0-9_]{0,47}", a["name"]):
                raise RouterError("Agent names must use the tvlk_ai_route_ prefix and a safe filename")
            names.append(a["name"])
            text(a["description"], role + ".description")
            text(a["instructions"], role + ".instructions")
        text(a["model"], role + ".model")
        if not re.fullmatch(r"[a-zA-Z0-9][a-zA-Z0-9._:-]{0,127}", a["model"]):
            raise RouterError("Invalid model identifier")
        if a["reasoning_effort"] not in ("none", "minimal", "low", "medium", "high", "xhigh", "max", "ultra"):
            raise RouterError("Unknown reasoning_effort")
    if len(set(names)) != 4:
        raise RouterError("Agent names must be unique")
    r = d["routing"]
    shape(r, ("max_active_executors", "max_escalations_per_request", "reuse_executor_for_followups", "on_unavailable", "rules"), "routing")
    if type(r["max_active_executors"]) is not int or r["max_active_executors"] != 1:
        raise RouterError("Only one active executor is supported")
    if type(r["max_escalations_per_request"]) is not int or not 0 <= r["max_escalations_per_request"] <= 1:
        raise RouterError("Escalations must be 0 or 1")
    if type(r["reuse_executor_for_followups"]) is not bool or r["on_unavailable"] != "stop_and_report":
        raise RouterError("Invalid reuse or failure policy")
    text(r["rules"], "routing.rules")
    shape(d["execution"], ("shared_instructions",), "execution")
    text(d["execution"]["shared_instructions"], "execution.shared_instructions")
    shape(d["backup"], ("directory", "additional_config_paths"), "backup")
    text(d["backup"]["directory"], "backup.directory")
    extras = d["backup"]["additional_config_paths"]
    if not isinstance(extras, list) or any(not isinstance(x, str) or not x for x in extras):
        raise RouterError("additional_config_paths must be a list of path strings")
    return d


def native_agents(d):
    out = {}
    for a in d["agents"].values():
        v = {"name": a["name"], "description": a["description"], "model": a["model"],
             "model_reasoning_effort": a["reasoning_effort"],
             "developer_instructions": d["execution"]["shared_instructions"].strip() + "\n\n" + a["instructions"].strip(),
             "agents": {"enabled": False}}
        out[a["name"] + ".toml"] = ("# Generated by TVLK-OpenAI-Router. Edit router.toml, then apply.\n" + tomlkit.dumps(v)).encode()
    return out


